import { readFileSync, writeFileSync } from 'node:fs';
const root = '/home/user/HealthPay-Medical-Discount-card/packages/db';
const files = ['migrations/0000_init.sql','migrations/0001_providers_and_taxonomy.sql'];
let stmts = [];
for (const f of files) {
  const sql = readFileSync(`${root}/${f}`,'utf8');
  for (const part of sql.split('--> statement-breakpoint')) {
    const s = part.trim();
    if (s) stmts.push(s);
  }
}
const gz = readFileSync(`${root}/src/seed-data/providers.json.gz`).toString('base64');
const out =
`/* AUTO-GENERATED by scripts/gen-embedded.mjs — do not edit by hand.
   Embeds the migration SQL + gzipped provider directory so the one-shot
   /api/v1/internal/db/setup route works in a serverless lambda without any
   filesystem access. Regenerate after schema or directory changes. */
/* eslint-disable */
export const MIGRATION_STATEMENTS: string[] = ${JSON.stringify(stmts, null, 0)};
export const PROVIDERS_GZ_B64 = ${JSON.stringify(gz)};
`;
writeFileSync(`${root}/src/embedded.ts`, out);
console.log('statements:', stmts.length, '| gz b64 chars:', gz.length, '| embedded.ts bytes:', out.length);
