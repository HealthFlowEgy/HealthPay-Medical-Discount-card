/* Regenerates packages/db/src/embedded.ts: all migration statements (in order)
   + the gzipped provider directory, so the one-shot DB setup route needs no
   filesystem access in the lambda. Run after schema/directory changes:
     node scripts/gen-embedded.mjs */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
const root = new URL('../packages/db/', import.meta.url).pathname;
const migDir = `${root}migrations`;
const files = readdirSync(migDir).filter((f) => f.endsWith('.sql')).sort();
const stmts = [];
for (const f of files) {
  for (const part of readFileSync(`${migDir}/${f}`, 'utf8').split('--> statement-breakpoint')) {
    const s = part.trim();
    if (s) stmts.push(s);
  }
}
const gz = readFileSync(`${root}src/seed-data/providers.json.gz`).toString('base64');
const out =
`/* AUTO-GENERATED by scripts/gen-embedded.mjs — do not edit by hand.
   Embeds the migration SQL + gzipped provider directory so the one-shot
   /api/v1/internal/db/setup route works in a serverless lambda without any
   filesystem access. Regenerate after schema or directory changes. */
/* eslint-disable */
export const MIGRATION_STATEMENTS: string[] = ${JSON.stringify(stmts)};
export const PROVIDERS_GZ_B64 = ${JSON.stringify(gz)};
`;
writeFileSync(`${root}src/embedded.ts`, out);
console.log('files:', files.join(', '), '| statements:', stmts.length, '| embedded.ts bytes:', out.length);
